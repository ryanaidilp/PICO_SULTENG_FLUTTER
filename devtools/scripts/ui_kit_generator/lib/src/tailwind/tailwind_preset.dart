// Self-contained on purpose: no imports. theme_builder/theme_engine keeps a
// byte-identical copy (dart2js cannot take this package, which uses dart:io).
// scripts/check_tailwind_renderer_sync.sh fails CI on any drift (ADR-033).

/// Light and dark Tailwind variables, keyed by CSS custom property name.
///
/// Names follow the Theme Builder's Tailwind exporter
/// (`theme_builder/lib/src/services/tailwind_exporter.dart`) so both outputs
/// can be swapped: `--color-primary-500`, `--color-bg`, `--text-body-large`,
/// `--spacing-xl2`, `--radius-md`, `--shadow-sm`, ...
typedef TailwindTokens = ({
  Map<String, String> light,
  Map<String, String> dark,
});

const _header = '''
/*
 * Tailwind CSS v4 theme preset, generated from the app's ui_kit by
 * `monorepo_toolkit ui-kit export-tailwind`. Do not edit; re-run the command.
 *
 * Light values live in @theme. Dark values override the same variables when
 * <html data-theme="dark"> is set, or by system preference unless
 * data-theme="light" is set.
 */
''';

// Blank line between token groups: a colour palette, the semantic colours, or
// another namespace (--text-*, --spacing-*, ...).
String _group(String name) {
  final m = RegExp(r'^--color-(\w+)-\d+$').firstMatch(name);
  if (m != null) return m[1]!;
  return name.startsWith('--color-')
      ? 'semantic'
      : RegExp(r'^--(font-weight|\w+)').firstMatch(name)![1]!;
}

String _vars(Map<String, String> vars, String indent) {
  final b = StringBuffer();
  String? last;
  for (final e in vars.entries) {
    final g = _group(e.key);
    if (last != null && g != last) b.writeln();
    last = g;
    b.writeln('$indent${e.key}: ${e.value};');
  }
  return b.toString();
}

/// Tailwind v4 CSS: `@theme` (light) plus dark-mode variable overrides.
///
/// [header] replaces the leading comment. The dark blocks are omitted when
/// `t.dark` is empty (a single-mode Theme Builder document).
String renderTailwindV4(TailwindTokens t, {String header = _header}) {
  final theme = '$header\n@theme {\n${_vars(t.light, '  ')}}\n';
  if (t.dark.isEmpty) return theme;
  final dark = _vars(t.dark, '    ');
  final darkAttr = dark.replaceAll(RegExp('^    ', multiLine: true), '  ');
  return '$theme\n'
      ':root[data-theme="dark"] {\n$darkAttr}\n\n'
      '@media (prefers-color-scheme: dark) {\n'
      '  :root:not([data-theme="light"]) {\n$dark  }\n}\n';
}

// `--font-weight-bold` is a weight, not a family; check it before `--font-`.
const _v3Header = '''
// Tailwind v3 theme.extend, generated by
// `monorepo_toolkit ui-kit export-tailwind`. Do not edit.
''';

const _v3Keys = <String, String>{
  '--color-': 'colors',
  '--font-weight-': 'fontWeight',
  '--font-': 'fontFamily',
  '--text-': 'fontSize',
  '--leading-': 'lineHeight',
  '--tracking-': 'letterSpacing',
  '--spacing-': 'spacing',
  '--radius-': 'borderRadius',
  '--shadow-': 'boxShadow',
};

/// Optional Tailwind v3 `theme.extend`. Values keep the CSS variable with the
/// light value as fallback, so dark mode needs only the dark blocks of the v4
/// CSS file (they are plain CSS and work under v3). [header] replaces the
/// leading comment.
String renderTailwindV3(TailwindTokens t, {String header = _v3Header}) {
  final groups = <String, List<String>>{};
  for (final e in t.light.entries) {
    final prefix = _v3Keys.keys.firstWhere(e.key.startsWith);
    final key = e.key.substring(prefix.length);
    groups
        .putIfAbsent(_v3Keys[prefix]!, () => [])
        .add("        '$key': 'var(${e.key}, ${e.value})',");
  }
  final b = StringBuffer()
    ..write(header)
    ..writeln('module.exports = {')
    ..writeln("  darkMode: ['selector', '[data-theme=\"dark\"]'],")
    ..writeln('  theme: {')
    ..writeln('    extend: {');
  for (final g in groups.entries) {
    b
      ..writeln('      ${g.key}: {')
      ..writeAll(g.value.map((l) => '$l\n'))
      ..writeln('      },');
  }
  b
    ..writeln('    },')
    ..writeln('  },')
    ..writeln('};');
  return b.toString();
}
